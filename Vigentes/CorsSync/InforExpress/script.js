const serviceImage = document.querySelector("#service-image");
const serviceLabel = document.querySelector("#service-label");
const serviceTitle = document.querySelector("#service-title");
const serviceText = document.querySelector("#service-text");
const serviceList = document.querySelector("#service-list");
const serviceTags = document.querySelector("#service-tags");
const serviceTabs = [...document.querySelectorAll(".service-tab")];
const portfolioGrid = document.querySelector("#portfolio-grid");
const videoScroller = document.querySelector("#video-scroller");
const videoArrowButtons = [...document.querySelectorAll("[data-video-scroll]")];
const mediaModal = document.querySelector("#media-modal");
const mediaModalContent = document.querySelector("#media-modal-content");
const mediaModalClose = document.querySelector(".media-modal-close");
const navToggle = document.querySelector(".nav-toggle");
const navLinks = document.querySelector(".nav-links");

function renderService(index) {
  const service = services[index];

  serviceImage.src = service.image;
  serviceImage.alt = service.imageAlt;
  serviceLabel.textContent = service.label;
  serviceTitle.textContent = service.title;
  serviceText.textContent = service.text;

  serviceList.innerHTML = service.bullets.map((item) => `<li>${item}</li>`).join("");
  serviceTags.innerHTML = service.tags.map((item) => `<span>${item}</span>`).join("");

  serviceTabs.forEach((tab, tabIndex) => {
    const isActive = tabIndex === index;
    tab.classList.toggle("is-active", isActive);
    tab.setAttribute("aria-selected", String(isActive));
  });
}

function renderPortfolio() {
  portfolioGrid.innerHTML = portfolioItems
    .map(
      (item) => `
        <article class="portfolio-item ${item.size}" tabindex="0" role="button" aria-label="${item.title}" data-type="image" data-src="${item.src}" data-alt="${item.alt}">
          <img src="${item.src}" alt="${item.alt}" loading="lazy" />
          <div class="portfolio-caption">
            <span>${item.label}</span>
            <strong>${item.title}</strong>
          </div>
        </article>
      `,
    )
    .join("");
}

function renderVideos() {
  videoScroller.innerHTML = videoItems
    .map(
      (src, index) => `
        <article class="video-card" tabindex="0" role="button" aria-label="Abrir vídeo ${index + 1} da Infor Express" data-type="video" data-src="${src}">
          <video muted playsinline preload="metadata" loop>
            <source src="${src}" type="video/mp4" />
          </video>
          <div class="video-card-copy">
            <span>Vídeo ${String(index + 1).padStart(2, "0")}</span>
            <strong>Infor Express em movimento</strong>
          </div>
        </article>
      `,
    )
    .join("");
}

function updateVideoArrows() {
  if (!videoScroller || !videoArrowButtons.length) {
    return;
  }

  const maxScrollLeft = videoScroller.scrollWidth - videoScroller.clientWidth;
  const atStart = videoScroller.scrollLeft <= 4;
  const atEnd = videoScroller.scrollLeft >= maxScrollLeft - 4;

  videoArrowButtons.forEach((button) => {
    const direction = Number(button.dataset.videoScroll);
    button.disabled = direction < 0 ? atStart : atEnd;
  });
}

function scrollVideos(direction) {
  if (!videoScroller) {
    return;
  }

  const firstCard = videoScroller.querySelector(".video-card");
  const gap = 16;
  const distance = firstCard ? firstCard.getBoundingClientRect().width + gap : videoScroller.clientWidth * 0.85;

  videoScroller.scrollBy({
    left: distance * direction,
    behavior: "smooth",
  });
}

function openMedia(type, src, alt = "") {
  mediaModalContent.innerHTML =
    type === "video"
      ? `
        <video controls autoplay playsinline>
          <source src="${src}" type="video/mp4" />
        </video>
      `
      : `<img src="${src}" alt="${alt}" />`;

  mediaModal.showModal();
}

serviceTabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    renderService(Number(tab.dataset.service));
  });
});

document.addEventListener("click", (event) => {
  const mediaCard = event.target.closest("[data-type]");
  if (mediaCard) {
    openMedia(mediaCard.dataset.type, mediaCard.dataset.src, mediaCard.dataset.alt);
  }
});

document.addEventListener("keydown", (event) => {
  const mediaCard = event.target.closest?.("[data-type]");
  if (mediaCard && (event.key === "Enter" || event.key === " ")) {
    event.preventDefault();
    openMedia(mediaCard.dataset.type, mediaCard.dataset.src, mediaCard.dataset.alt);
  }

  if (event.key === "Escape" && mediaModal.open) {
    mediaModal.close();
  }
});

mediaModalClose.addEventListener("click", () => {
  mediaModal.close();
});

mediaModal.addEventListener("close", () => {
  mediaModalContent.innerHTML = "";
});

mediaModal.addEventListener("click", (event) => {
  if (event.target === mediaModal) {
    mediaModal.close();
  }
});

navToggle?.addEventListener("click", () => {
  const expanded = navToggle.getAttribute("aria-expanded") === "true";
  navToggle.setAttribute("aria-expanded", String(!expanded));
  navLinks.classList.toggle("is-open");
});

navLinks?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    navToggle?.setAttribute("aria-expanded", "false");
    navLinks.classList.remove("is-open");
  });
});

videoArrowButtons.forEach((button) => {
  button.addEventListener("click", () => {
    scrollVideos(Number(button.dataset.videoScroll));
  });
});

videoScroller?.addEventListener("scroll", updateVideoArrows);

window.addEventListener("resize", updateVideoArrows);

document.addEventListener("mouseover", (event) => {
  const card = event.target.closest(".video-card");
  if (!card) {
    return;
  }

  const video = card.querySelector("video");
  video?.play().catch(() => {});
});

document.addEventListener("mouseout", (event) => {
  const card = event.target.closest(".video-card");
  if (!card) {
    return;
  }

  const video = card.querySelector("video");
  if (video) {
    video.pause();
    video.currentTime = 0;
  }
});

document.addEventListener("focusin", (event) => {
  const card = event.target.closest(".video-card");
  if (!card) {
    return;
  }

  const video = card.querySelector("video");
  video?.play().catch(() => {});
});

document.addEventListener("focusout", (event) => {
  const card = event.target.closest(".video-card");
  if (!card) {
    return;
  }

  const video = card.querySelector("video");
  if (video) {
    video.pause();
    video.currentTime = 0;
  }
});

